# Shell aliases.
#
# Installed to ~/.config/minsoft1115/bash/ by install-bash-config.sh and sourced
# from ~/.bashrc. It loads after Omarchy's own bash rc, so anything defined here
# overrides a stock alias of the same name.
#
# Keep this file to alias definitions; a function gets its own file, named after
# it. Files load in filename order, and bash expands aliases as it reads a
# function body -- so an alias here is already in effect inside every function
# file that sorts after this one.

